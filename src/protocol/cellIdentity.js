const YEAR_SEQ = "FGHJKLMNPRSTVWXY123456789ABCDE";
const MONTH_SEQ = "123456789ABC";
const DAY_SEQ = "123456789ABCDEFGHJKLMNPRSTVWXY0";

export function parseBatteryIdString(rawId) {
  if (!rawId || typeof rawId !== "string") return null;
  const cleaned = rawId.replace(/\s+/g, "");
  if (cleaned.length < 9) return null;

  const fixedPart = cleaned.slice(0, 9);
  let rest = cleaned.slice(9);
  let ladderCode = "";
  if (rest.startsWith("-R-")) {
    ladderCode = "-R";
    rest = rest.slice(3);
  } else if (rest.startsWith("R-")) {
    ladderCode = "-R";
    rest = rest.slice(2);
  }

  const enterpriseCode = fixedPart.slice(0, 4);
  const productTypeCode = fixedPart[4];
  const chemistryCode = fixedPart[5];
  const yIdx = YEAR_SEQ.indexOf(fixedPart[6]);
  const mIdx = MONTH_SEQ.indexOf(fixedPart[7]);
  const dIdx = DAY_SEQ.indexOf(fixedPart[8]);
  const productionDate =
    yIdx >= 0 && mIdx >= 0 && dIdx >= 0
      ? `${2025 + yIdx}-${String(mIdx + 1).padStart(2, "0")}-${String(dIdx + 1).padStart(2, "0")}`
      : "--";

  const miCode = rest.length >= 5 ? rest.slice(2, 5) : "";
  const entry = MI_CODE_TABLE[miCode] || null;
  const miCodeInfo = entry
    ? { project: entry.projects.join("/"), supplier: entry.supplier, cellModel: entry.cellModel }
    : { project: "--", supplier: "--", cellModel: "--" };

  return {
    raw: rawId,
    fixed: {
      enterpriseCode,
      assemblyFactory: ENTERPRISE_NAMES_ZH[enterpriseCode] || "--",
      assemblyFactoryEn: ENTERPRISE_NAMES_EN[enterpriseCode] || "--",
      productType: PRODUCT_TYPE_MAP[productTypeCode] || "--",
      batteryType: BATTERY_CHEMISTRY_MAP[chemistryCode] || "--",
      productionDate,
    },
    ladderCode: ladderCode || "--",
    miCode,
    compositeKey: `${enterpriseCode}${miCode}`,
    miCodeInfo,
  };
}
